static void
alac_bad_params_test (void)
{	static const struct
	{	const unsigned char	*data ;
		unsigned int		len ;
	} tests [] =
	{	{	alac_bad_params_1, sizeof (alac_bad_params_1)	},
		{	alac_bad_params_2, sizeof (alac_bad_params_2)	},
		} ;
	/* kb in the magic cookie : 8 (header) + 12 + 32 ('desc') + 12 ('kuki') + 8. */
	const unsigned int	kb_offset = 72 ;
	const char		*filename = "bad_alac_params.caf" ;
	unsigned char	data [2048] ;
	int				buffer [256] ;
	SNDFILE			*sndfile ;
	SF_INFO			sfinfo ;
	sf_count_t		count ;
	unsigned		k ;

	print_test_name (__func__, filename) ;

	for (k = 0 ; k < ARRAY_LEN (tests) ; k++)
	{	exit_if_true (tests [k].len > sizeof (data),
			"\n\nLine %d : test data (%u bytes) does not fit the buffer.\n", __LINE__, tests [k].len
			) ;

		/* A kb of zero is refused when the file is opened. */
		dump_data_to_file (filename, tests [k].data, tests [k].len) ;

		memset (&sfinfo, 0, sizeof (sfinfo)) ;
		sndfile = sf_open (filename, SFM_READ, &sfinfo) ;
		exit_if_true (sndfile != NULL,
			"\n\nLine %d : sf_open ('%s') with kb 0 should have failed.\n", __LINE__, filename
			) ;

		/* With a valid kb, the first frame is refused and nothing is read. */
		memcpy (data, tests [k].data, tests [k].len) ;
		data [kb_offset] = 14 ;
		dump_data_to_file (filename, data, tests [k].len) ;

		memset (&sfinfo, 0, sizeof (sfinfo)) ;
		sndfile = sf_open (filename, SFM_READ, &sfinfo) ;
		exit_if_true (sndfile == NULL,
			"\n\nLine %d : sf_open ('%s') failed : %s\n", __LINE__, filename, sf_strerror (NULL)
			) ;

		count = sf_read_int (sndfile, buffer, ARRAY_LEN (buffer)) ;
		exit_if_true (count != 0,
			"\n\nLine %d : sf_read_int returned %d samples from an invalid frame.\n", __LINE__, (int) count
			) ;

		sf_close (sndfile) ;
		} ;

	unlink (filename) ;

	puts ("ok") ;
} /* alac_bad_params_test */

